"""Turn a choice analysis into a walkthrough - as a mod, and as a document.

The mod is a single `.rpy` dropped into the game's folder. It wraps
`renpy.exports.menu`, which is what `Menu.execute` calls on both Ren'Py 7 and 8
with the identical signature `(choices, set_expr, args, kwargs,
item_arguments)`. Each entry in `choices` is `(caption, condition, index)`
where `index` is the option's position in the original `menu` statement - the
same index the analyser recorded - so annotations line up exactly.

Menus are identified at runtime by `renpy.get_filename_line()`, which returns
the location of the executing statement. Matching that against the AST node's
own filename and line number is unambiguous, unlike matching on caption text
which breaks as soon as a game reuses "Yes" and "No".

The generated file has to run under Python 2 as well, because Ren'Py 7 games
are still common - so no f-strings, and every string literal is written as an
escaped `u"..."`.
"""

from __future__ import annotations

import html
import json
from datetime import datetime
from pathlib import Path

from ...core.fsutil import atomic_write
from .analyze import Analysis, Choice, MenuPoint, looks_like_ending

MOD_FILENAME = "nodex_walkthrough.rpy"
#: Late enough to win against anything the game sets up itself.
INIT_PRIORITY = 1999
DEFAULT_COLOUR = "#7fdc7f"


def _py_string(value: str) -> str:
    """Emit a Python 2/3 compatible unicode literal."""
    out = []
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif 32 <= ord(char) < 127:
            out.append(char)
        else:
            out.append("\\u%04x" % ord(char))
    return 'u"%s"' % "".join(out)


def _escape_renpy_text(value: str) -> str:
    """Neutralise Ren'Py's text markup in generated captions.

    `[name]` interpolates a variable and `{b}` starts a tag; a variable value
    containing either would corrupt the menu at best and crash it at worst.
    """
    return value.replace("[", "[[").replace("{", "{{")


def annotation_for(choice: Choice, colour: str = DEFAULT_COLOUR) -> str:
    """The text appended to a choice's caption in game."""
    parts = [effect.describe() for effect in choice.effects]
    for target in choice.jumps + choice.calls:
        parts.append("-> " + target)
    if not parts:
        parts = [effect.describe() for effect in choice.downstream[:2]]
    if not parts:
        return ""

    text = ", ".join(parts[:4])
    return "{color=%s}(%s){/color}" % (colour, _escape_renpy_text(text))


def build_annotations(analysis: Analysis) -> dict[str, dict[int, str]]:
    """Map `filename:line` to per-index annotation text."""
    table: dict[str, dict[int, str]] = {}
    for menu in analysis.menus:
        entries = {}
        for choice in menu.choices:
            text = annotation_for(choice)
            if text:
                entries[choice.index] = text
        if entries:
            table[menu.key] = entries
    return table


def build_mod(analysis: Analysis, colour: str = DEFAULT_COLOUR) -> str:
    """Render the walkthrough mod's source."""
    table = build_annotations(analysis)

    lines = [
        "# Generated by Nodex on %s." % datetime.now().strftime("%Y-%m-%d %H:%M"),
        "#",
        "# Annotates each menu choice with the variables it changes and where it",
        "# leads. Delete this file to remove the mod - it changes nothing else.",
        "#",
        "# %d menu(s) annotated across %d script(s)."
        % (len(table), analysis.scripts_read),
        "",
        "init %d python:" % INIT_PRIORITY,
        "",
        "    _nodex_annotations = {",
    ]

    for key in sorted(table):
        entries = table[key]
        rendered = ", ".join(
            "%d: %s" % (index, _py_string(entries[index])) for index in sorted(entries)
        )
        lines.append("        %s: {%s}," % (_py_string(key), rendered))

    lines.extend(
        [
            "    }",
            "",
            "    def _nodex_annotate(items):",
            "        try:",
            "            filename, line = renpy.get_filename_line()",
            "        except Exception:",
            "            return items",
            "",
            '        table = _nodex_annotations.get("%s:%s" % (filename, line))',
            "        if not table:",
            "            return items",
            "",
            "        annotated = []",
            "        for entry in items:",
            "            try:",
            "                caption, condition, value = entry",
            "            except Exception:",
            "                annotated.append(entry)",
            "                continue",
            "            note = table.get(value)",
            "            if note and caption:",
            '                caption = caption + " " + note',
            "            annotated.append((caption, condition, value))",
            "        return annotated",
            "",
            "    def _nodex_menu(items, *args, **kwargs):",
            "        try:",
            "            items = _nodex_annotate(items)",
            "        except Exception:",
            "            pass",
            "        return _nodex_original_menu(items, *args, **kwargs)",
            "",
            "    # Patch once, even if this init block is re-entered.",
            '    if not getattr(renpy.exports, "_nodex_patched", False):',
            "        _nodex_original_menu = renpy.exports.menu",
            "        renpy.exports.menu = _nodex_menu",
            "        renpy.exports._nodex_patched = True",
            "",
        ]
    )

    return "\n".join(lines)


def install_mod(
    analysis: Analysis, game_dir: Path | str | None = None, colour: str = DEFAULT_COLOUR
) -> Path:
    """Write the mod into the game's folder. Returns the path written."""
    target = Path(game_dir) if game_dir is not None else analysis.game_dir
    destination = target / MOD_FILENAME
    atomic_write(destination, build_mod(analysis, colour).encode("utf-8"))
    _clear_stale_compiled(destination)
    return destination


def _clear_stale_compiled(mod_path: Path) -> None:
    """Drop a previously compiled copy so Ren'Py recompiles the new source."""
    compiled = mod_path.with_suffix(".rpyc")
    if compiled.exists():
        try:
            compiled.unlink()
        except OSError:
            pass


def uninstall_mod(game_dir: Path | str) -> list[Path]:
    """Remove the mod and its compiled form. Returns what was deleted."""
    game_dir = Path(game_dir)
    removed = []
    for candidate in (game_dir / MOD_FILENAME, (game_dir / MOD_FILENAME).with_suffix(".rpyc")):
        if candidate.exists():
            try:
                candidate.unlink()
                removed.append(candidate)
            except OSError:
                pass
    return removed


