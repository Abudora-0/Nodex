def _choice_rows(menu: MenuPoint) -> str:
    rows = []
    for choice in menu.choices:
        effects = "".join(
            '<span class="eff">%s</span>' % html.escape(effect.describe())
            for effect in choice.effects
        )
        routes = "".join(
            '<span class="route %s">%s</span>'
            % ("ending" if looks_like_ending(target) else "", html.escape(target))
            for target in choice.jumps + choice.calls
        )
        downstream = ""
        if not effects and choice.downstream:
            downstream = '<span class="later">later: %s</span>' % html.escape(
                ", ".join(e.describe() for e in choice.downstream[:3])
            )
        if not (effects or routes or downstream):
            effects = '<span class="none">no effect</span>'

        condition = (
            '<span class="cond">if %s</span>' % html.escape(choice.condition)
            if choice.condition
            else ""
        )

        rows.append(
            "<tr><td class=\"cap\">%s%s</td><td>%s%s%s</td></tr>"
            % (
                html.escape(choice.caption) or "<em>(blank)</em>",
                condition,
                effects,
                routes,
                downstream,
            )
        )
    return "".join(rows)


def build_html(analysis: Analysis, title: str = "Walkthrough") -> str:
    """Render a self-contained walkthrough document."""
    # Every menu with options is included. A choice that only leads to
    # different dialogue still matters to a reader, and filtering those out
    # would drop most of the choice points in some games.
    menus = [menu for menu in analysis.menus if menu.choices]
    blocks = []

    for menu in menus:
        heading = menu.label or "(no label)"
        blocks.append(
            '<section class="menu%s" data-search="%s" data-meaningful="%d">'
            '<h3>%s <span class="loc">%s:%d</span></h3>'
            "<table>%s</table></section>"
            % (
                "" if menu.meaningful else " minor",
                html.escape(
                    " ".join(
                        [heading, menu.filename]
                        + [c.caption for c in menu.choices]
                        + [e.variable for c in menu.choices for e in c.effects]
                    ).lower()
                ),
                1 if menu.meaningful else 0,
                html.escape(heading),
                html.escape(menu.filename),
                menu.linenumber,
                _choice_rows(menu),
            )
        )

    variables = "".join(
        "<li><b>%s</b> <span>%d</span></li>" % (html.escape(name), count)
        for name, count in analysis.tracked_variables[:40]
    )

    return _HTML_TEMPLATE % {
        "title": html.escape(title),
        "generated": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "menu_count": len(analysis.meaningful_menus),
        "total_menus": len(menus),
        "script_count": analysis.scripts_read,
        "variable_count": len(analysis.variables),
        "variables": variables,
        "menus": "".join(blocks),
    }


